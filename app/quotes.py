_used_quotes: dict[str, set[int]] = {}


def daily_quote(scope_id: str) -> str:
    """为当前会话随机返回一句，连续调用不会重复，群之间互不共享记录。"""
    scope = str(scope_id)
    used = _used_quotes.setdefault(scope, set())
    if len(used) >= len(QUOTES):
        used.clear()
    candidates = [index for index in range(len(QUOTES)) if index not in used]
    index = random.SystemRandom().choice(candidates)
    used.add(index)
    return QUOTES[index]
