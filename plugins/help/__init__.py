        "/清除记忆 - 清除当前群或当前私聊的 AI 记忆\n"
        "/语音 文本 - 让 Bot 用语音说这句话\n"
        "/表情 [情绪] - 查看或发送表情包\n"
        "/天气 城市 \n"
        "/一言 - 获取今日一句\n"
        "/锐评 内容/图片 \n"
        "/锐评头像 @成员 \n"
        "/点歌 歌名/歌手/歌手 歌名\n"
        "/今日运势 \n"
        "/塔罗 问题 \n"
        "/签到 \n"
        "/轮盘赌 - 单人轮盘赌\n"
        "/轮盘赌 多人/加入/开始/开枪 - 多人轮盘赌\n"
        "/21点 创建/加入/开始 - 创建多人 21 点\n"
