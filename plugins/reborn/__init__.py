def _name(event: MessageEvent) -> str:
    sender = getattr(event, "sender", None)
    return getattr(sender, "card", None) or getattr(sender, "nickname", None) or str(event.user_id)


async def _send(bot: Bot, event: MessageEvent, message: str) -> None:
    group_id = getattr(event, "group_id", None)
    if group_id is not None:
        await bot.send_group_msg(group_id=group_id, message=message)
    else:
        await bot.send_private_msg(user_id=event.user_id, message=message)


@reborn.handle()
async def handle_reborn(bot: Bot, event: MessageEvent) -> None:
    origin_name, origin_story = random.choice(_ORIGINS)
    talent = random.choice(_TALENTS)
    encounter = random.choice(_ENCOUNTERS)
    ending = random.choice(_ENDINGS)
    age = random.randint(52, 117)
    name = _name(event)

    story = (
        f"【投胎模拟器｜{name} 的新人生】\n"
        f"投胎结果：{origin_name}\n\n"
        f"你出生时，{origin_story}。\n"
        f"你的天赋是：{talent}。\n\n"
        f"少年时期，你一边适应身世，一边凭借这项天赋闯出了自己的小天地。"
        f"你经历过失败，也曾因为害怕而错过机会，但每一次跌倒都让你更清楚自己想成为什么样的人。\n\n"
        f"人生转折：{encounter}\n\n"
        f"你活到了 {age} 岁。{ending}\n\n"
        "本次投胎评价：人生没有标准答案，能把自己的故事过完，就是隐藏结局。"
    )
    await _send(bot, event, story)
